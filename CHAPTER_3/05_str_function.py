# 1/ LEN FUNCTION
name = "likun"
print(len(name))

# 2/ STRING.ENDSWITH() FUNCTION
name = "likun"
print(name.endswith("kun"))

# 3/ STRING.STARTSWITH() FUNCTION
print(name.startswith("li"))


# 4/ STRING.CAPITALIZE() FUNCTION 
print(name.capitalize())

# 5/ STRING.FIND(WORD) FUNCTION
print(name.find("k"))

# 6/ STRING.REPLACE FUNCTION
print(name.replace("likun","sudu"))